# Trial 7, capture fidelity: does Continuum record everything a real Claude Code agent does?
#   run.sh WORKDIR CLAUDE_WRAPPER [MODEL]
# One turn in real Claude Code with only Continuum's hooks: failing tests, a file edit, a
# script that writes a file, a subagent, a project skill and an MCP server that writes
# outside the repository. check.py then compares the journal with Claude Code's own
# transcripts, call by call, and reports the hooks' latency.
set -euo pipefail
WORK="$(mkdir -p "$1" && cd "$1" && pwd)"; CL="$2"; MODEL="${3:-sonnet}"
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(git -C "$HERE" rev-parse --show-toplevel)"
PY="$REPO/.venv/bin/python"
P="$WORK/proj"; SCHEMA=trial7
DB=postgresql://continuum:continuum@localhost:5432/continuum
rm -rf "$P" "$WORK/home" "$WORK/hook-times.log" "$WORK/tickets.json" && mkdir -p "$P/.claude"
git -C "$P" init -q -b main
git -C "$P" remote add origin https://example.com/acme/invoicer.git
"$PY" "$HERE/../debug_handoff/fixture.py" "$P"
mkdir -p "$P/tools" "$P/.claude/skills/release-notes"
cat > "$P/tools/gen.py" <<'PYEOF'
"""Regenerate invoicer/rates_table.py from the published VAT rates."""
from pathlib import Path
RATES = {"DE": "0.19", "FR": "0.20", "NL": "0.21"}
Path("invoicer/rates_table.py").write_text(
    "# generated by tools/gen.py\nRATES = " + repr(RATES) + "\n")
print("wrote invoicer/rates_table.py")
PYEOF
printf '# TODO: support CHF\n' >> "$P/invoicer/parse.py"
printf '# TODO: per-line VAT rounding\n' >> "$P/invoicer/totals.py"
cat > "$P/.claude/skills/release-notes/SKILL.md" <<'MDEOF'
---
name: release-notes
description: Write RELEASE_NOTES.md for this repository's latest changes. Use when asked for release notes.
---
Write `RELEASE_NOTES.md` at the repository root with a `## Unreleased` heading and one
bullet per user-visible change, in plain language. Do not list internal refactors.
MDEOF
cat > "$WORK/timed-hook.sh" <<SHEOF
#!/usr/bin/env bash
payload=\$(cat)
s=\$(date +%s%N)
printf '%s' "\$payload" | continuum hook claude-code
e=\$(date +%s%N)
ev=\$(printf '%s' "\$payload" | python3 -c 'import json,sys; d=json.load(sys.stdin); print(d.get("hook_event_name"), d.get("tool_name", ""))' 2>/dev/null)
echo "\$(( (e - s) / 1000000 )) \$ev" >> "$WORK/hook-times.log"
SHEOF
chmod +x "$WORK/timed-hook.sh"
"$PY" - "$REPO/integrations/claude-code/hooks/hooks.json" "$P/.claude/settings.json" "$WORK/timed-hook.sh" <<'PYEOF'
import json, sys
hooks = json.load(open(sys.argv[1]))["hooks"]
for groups in hooks.values():
    for g in groups:
        for h in g["hooks"]:
            h["command"] = sys.argv[3]
json.dump({"hooks": hooks}, open(sys.argv[2], "w"), indent=2)
PYEOF
cat > "$WORK/mcp.json" <<JSONEOF
{"mcpServers": {"tickets": {"command": "$PY", "args": ["$HERE/tickets_mcp.py"],
  "env": {"TICKETS_FILE": "$WORK/tickets.json"}}}}
JSONEOF
git -C "$P" -c user.email=t@e.x -c user.name=t add -A
git -C "$P" -c user.email=t@e.x -c user.name=t commit -qm "invoicer"
psql "$DB" -qc "DROP SCHEMA IF EXISTS $SCHEMA CASCADE" 2>/dev/null
cd "$P"
"$CL" CONTINUUM_DB_SCHEMA=$SCHEMA CONTINUUM_HOME="$WORK/home" claude -p "$(cat "$HERE/prompt.md")" \
  --model "$MODEL" --dangerously-skip-permissions --output-format json \
  --mcp-config "$WORK/mcp.json" > "$WORK/a.json" 2> "$WORK/a.err" || true
# the background drainer finishes the spool
for _ in $(seq 1 60); do
  [ -z "$(ls "$WORK/home/spool/"*.json 2>/dev/null)" ] && break; sleep 1
done
CONTINUUM_DATABASE_URL=$DB CONTINUUM_DB_SCHEMA=$SCHEMA CONTINUUM_HOME="$WORK/home" \
  "$PY" "$HERE/check.py" "$WORK" | tee "$WORK/check.txt"
